export function useI18n() {
  const locale = computed(() => language.value === 'en' ? 'en-US' : 'id-ID')

  function t(key: string, params: Record<string, string | number> = {}) {
    const template = messages[language.value][key] ?? messages.id[key] ?? key
    return Object.entries(params).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template)
  }

  function setLanguage(nextLanguage: Language) {
    language.value = nextLanguage
    localStorage.setItem(storageKey, nextLanguage)
    document.documentElement.lang = nextLanguage
  }

  function toggleLanguage() {
    setLanguage(language.value === 'id' ? 'en' : 'id')
  }

  if (document.documentElement.lang !== language.value) document.documentElement.lang = language.value

  return { language, locale, t, setLanguage, toggleLanguage }
}
